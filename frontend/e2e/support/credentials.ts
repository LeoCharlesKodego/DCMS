import { execFileSync } from 'node:child_process'
import { readFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))

/** Restores the seeded read/unread notification pair so each engine starts equal. */
export function seedNotifications() {
  execFileSync('bash', [resolve(here, '../../../backend/scripts/dev-local.sh'), '--notifications-only'], { stdio: 'pipe' })
}

/** Rebuilds the fictional sample documents so lifecycle tests start from a known state. */
export function seedSampleDocuments() {
  execFileSync('bash', [resolve(here, '../../../backend/scripts/dev-local.sh'), '--samples-only'], { stdio: 'pipe', timeout: 180_000 })
}

/** Credentials generated by backend/scripts/dev-local.sh. Never committed. */
export function localCredentials(): { email: string; password: string } {
  const file = resolve(here, '../../../backend/.env.dev-local')
  const values: Record<string, string> = {}

  for (const line of readFileSync(file, 'utf8').split(/\r?\n/)) {
    const match = line.match(/^([A-Z0-9_]+)=(.*)$/)
    if (match) values[match[1]] = match[2]
  }

  if (!values.DCMS_DEV_EMAIL || !values.DCMS_DEV_PASSWORD) {
    throw new Error('backend/.env.dev-local is missing. Run backend/scripts/dev-local.sh --prepare-only first.')
  }

  return { email: values.DCMS_DEV_EMAIL, password: values.DCMS_DEV_PASSWORD }
}
